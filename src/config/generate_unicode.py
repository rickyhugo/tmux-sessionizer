"""Regenerate shell variable-name ranges with the pinned Rust Unicode database."""

from pathlib import Path
import subprocess
import tempfile


SOURCE = r"""
fn main() {
    println!("// Generated by generate_unicode.py with Rust Unicode {:?}.", char::UNICODE_VERSION);
    println!("pub const ranges = [_][2]u21{{");
    let mut start = None;
    for n in 0..=0x110000u32 {
        let member = char::from_u32(n).is_some_and(char::is_alphanumeric);
        if member && start.is_none() { start = Some(n); }
        if !member {
            if let Some(first) = start.take() {
                println!("    .{{ 0x{:X}, 0x{:X} }},", first, n - 1);
            }
        }
    }
    println!("}};");
}
"""

with tempfile.TemporaryDirectory(prefix="tms-unicode-") as directory:
    binary = Path(directory) / "generate"
    subprocess.run(
        ["rustc", "--edition=2021", "-O", "-o", str(binary), "-"],
        input=SOURCE,
        text=True,
        check=True,
    )
    output = subprocess.check_output([str(binary)], text=True)
    Path(__file__).with_name("unicode_alphanumeric.zig").write_text(output)
