#!/usr/bin/env python3
"""Regenerate pinned Nucleo and Unicode tables. Development-only Rust toolchain."""

import hashlib
import io
import os
from pathlib import Path
import subprocess
import tarfile
import tempfile
import urllib.request


ROOT = Path(__file__).resolve().parents[1]
CRATES = {
    "nucleo-matcher-0.3.1": "bf33f538733d1a5a3494b836ba913207f14d9d4a1d3cd67030c5061bdd2cac85",
    "unicode-segmentation-1.12.0": "f6ccf251212114b54433ec949fd6a7841275f9ada20dddd2f29e9ceea4501493",
}
RUST_COMMIT = "b940084d7eb6a299eb4bfeb8e34901bc051e7ac4"


def unpack(crate, checksum, destination):
    cargo = Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo"))
    cached = list((cargo / "registry/cache").glob(f"*/{crate}.crate"))
    if cached:
        data = cached[0].read_bytes()
    else:
        name, version = crate.rsplit("-", 1)
        url = f"https://static.crates.io/crates/{name}/{name}-{version}.crate"
        with urllib.request.urlopen(url) as response:
            data = response.read()
    if hashlib.sha256(data).hexdigest() != checksum:
        raise SystemExit(f"Checksum mismatch for {crate}")
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
        archive.extractall(destination, filter="data")
    return destination / crate


def main():
    version = subprocess.check_output(
        ["mise", "exec", "rust@1.99.0", "--", "rustc", "-vV"], text=True
    )
    if f"commit-hash: {RUST_COMMIT}\n" not in version:
        raise SystemExit("Table generation requires the pinned Rust 1.99.0 compiler")
    with tempfile.TemporaryDirectory(prefix="tms-unicode-") as temporary:
        directory = Path(temporary)
        matcher, segmentation = [
            unpack(crate, checksum, directory) for crate, checksum in CRATES.items()
        ]
        source = directory / "generate.rs"
        source.write_text(
            f'#[path = "{matcher}/src/chars/normalize.rs"] mod normalize;\n'
            f'#[path = "{matcher}/src/chars/case_fold.rs"] mod case_fold;\n'
            f'#[path = "{segmentation}/src/tables.rs"] mod tables;\n'
            + r"""
fn main() {
    eprintln!("Rust character properties use Unicode {:?}", char::UNICODE_VERSION);
    for i in 0..=0x10ffff {
        let Some(c) = char::from_u32(i) else { continue };
        let fold = case_fold::CASE_FOLDING_SIMPLE.binary_search_by_key(&c, |p| p.0);
        let lower = fold.map_or(c, |j| case_fold::CASE_FOLDING_SIMPLE[j].1);
        let class = if c.is_lowercase() { 3 }
            else if fold.is_ok() { 4 }
            else if c.is_numeric() { 6 }
            else if c.is_alphabetic() { 5 }
            else if c.is_whitespace() { 0 }
            else { 1 };
        let category = tables::grapheme::grapheme_category(c).2 as u8;
        let incb = tables::derived_property::InCB_Extend(c);
        println!("{i:x} {class} {category} {} {:x} {:x}",
            incb as u8, lower as u32, normalize::normalize(c) as u32);
    }
}
"""
        )
        binary = directory / "generate"
        subprocess.run(
            [
                "mise",
                "exec",
                "rust@1.99.0",
                "--",
                "rustc",
                "--edition=2021",
                "-O",
                str(source),
                "-o",
                str(binary),
            ],
            check=True,
        )
        rows = [
            [
                int(value, base)
                for value, base in zip(line.split(), [16, 10, 10, 10, 16, 16])
            ]
            for line in subprocess.check_output([str(binary)], text=True).splitlines()
        ]
        output = [
            "// Generated by scripts/generate-matcher-tables.py.",
            "// Nucleo matcher 0.3.1 translations are MPL-2.0.",
            "// Unicode segmentation 1.12.0 is MIT OR Apache-2.0.",
            "// Rust character-property data is Unicode-3.0.",
            "// Copyright 2012-2018 The Rust Project Developers.",
            "// See vendor/licenses/matcher/ for licenses and provenance.",
            "",
            "pub const Range = struct { lo: u21, hi: u21, value: u8 };",
            "pub const Mapping = struct { from: u21, to: u21 };",
            "",
        ]
        for name, column, default in [
            ("classes", 1, 1),
            ("graphemes", 2, 0),
            ("incb_extend", 3, 0),
        ]:
            ranges = []
            for row in rows:
                cp, value = row[0], row[column]
                if value == default:
                    continue
                if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == value:
                    ranges[-1][1] = cp
                else:
                    ranges.append([cp, cp, value])
            output.append(f"pub const {name} = [_]Range{{")
            output.extend(
                f"    .{{ .lo = 0x{lo:x}, .hi = 0x{hi:x}, .value = {value} }},"
                for lo, hi, value in ranges
            )
            output.append("};\n")
        for name, column in [("case_fold", 4), ("normalize", 5)]:
            output.append(f"pub const {name} = [_]Mapping{{")
            output.extend(
                f"    .{{ .from = 0x{row[0]:x}, .to = 0x{row[column]:x} }},"
                for row in rows
                if row[0] != row[column]
            )
            output.append("};\n")
        (ROOT / "src/matcher/tables.zig").write_text("\n".join(output))
        licenses = ROOT / "vendor/licenses/matcher"
        licenses.mkdir(parents=True, exist_ok=True)
        for source_name, target_name in [
            (matcher / "LICENSE", "nucleo-MPL-2.0.txt"),
            (segmentation / "LICENSE-MIT", "unicode-MIT.txt"),
            (segmentation / "LICENSE-APACHE", "unicode-Apache-2.0.txt"),
            (segmentation / "COPYRIGHT", "unicode-COPYRIGHT.txt"),
        ]:
            (licenses / target_name).write_bytes(source_name.read_bytes())


if __name__ == "__main__":
    main()
